mod parse;

use parse::{parse_row, parse_substitution, sort_code_rust};
use std::{env, fmt::Write as _, fs, path::Path};

const WEIGHT_TABLE_PATH: &str = "data/valacdos.txt";
const SUBSTITUTIONS_TABLE_PATH: &str = "data/scsubtab.txt";

fn main() {
    // println!("cargo::rerun-if-changed=data/valacdos.txt");
    // println!("cargo::rerun-if-changed=data/scsubtab.txt");
    let mut out = String::from("// @generated by build/main.rs from data/*.txt. Do not edit.\n\n");

    let weights = fs::read_to_string(WEIGHT_TABLE_PATH)
        .unwrap_or_else(|e| panic!("failed to read {WEIGHT_TABLE_PATH}: {e}"));
    out.push_str("pub(crate) static WEIGHTS: &[WeightRow] = &[\n");

    for (index, line) in weights.lines().enumerate() {
        if line.trim().is_empty() {
            continue;
        }
        let row = parse_row(line)
            .unwrap_or_else(|e| panic!("{WEIGHT_TABLE_PATH} line {}: {e}", index + 1));
        writeln!(out, "{}", row.to_rust()).unwrap();
    }
    out.push_str("];\n\n");

    let subs = fs::read_to_string(SUBSTITUTIONS_TABLE_PATH)
        .unwrap_or_else(|e| panic!("failed to read {SUBSTITUTIONS_TABLE_PATH}: {e}"));

    let mut pairs: Vec<(u32, u32)> = subs
        .lines()
        .enumerate()
        .filter(|(_, line)| !line.trim().is_empty())
        .map(|(index, line)| {
            parse_substitution(line)
                .unwrap_or_else(|e| panic!("{SUBSTITUTIONS_TABLE_PATH} line {}: {e}", index + 1))
        })
        .collect();
    pairs.sort_by_key(|&(original, _)| original);
    for pair in pairs.windows(2) {
        assert!(
            pair[0].0 != pair[1].0,
            "duplicate substitution for {:06}",
            pair[0].0
        );
    }

    out.push_str("pub(crate) static SUBSTITUTIONS: &[(SortCode, SortCode)] = &[\n");
    for (original, substitute) in &pairs {
        writeln!(
            out,
            "    ({}, {}),",
            sort_code_rust(*original),
            sort_code_rust(*substitute)
        )
        .unwrap();
    }
    out.push_str("];\n");

    let path = Path::new(&env::var("OUT_DIR").unwrap()).join("tables.rs");
    fs::write(path, out).unwrap();
}
